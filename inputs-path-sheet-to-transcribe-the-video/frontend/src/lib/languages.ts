export function searchLanguages(query: string, options: LanguageOption[]): LanguageOption[] {
  const q = query.trim().toLowerCase();
  if (!q) return options;
  return options.filter(
    (l) => l.label.toLowerCase().includes(q) || l.value.toLowerCase().includes(q)
  );
}
